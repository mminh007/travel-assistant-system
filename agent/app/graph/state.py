# app/graph/state.py
from typing import Annotated, Optional, Sequence, List, Dict, Any
from typing_extensions import TypedDict
from langchain_core.messages import BaseMessage
from langgraph.graph.message import add_messages

class AgentState(TypedDict):
    # add_messages automatically appends new messages to the existing sequence
    messages: Annotated[Sequence[BaseMessage], add_messages]
    user_id: Optional[str]
    session_id: Optional[str]
    # ─── PHASE 1: GUARDRAIL & INTENT CLASSIFICATION ───
    is_in_domain: Optional[bool]     # True if travel related, False otherwise
    intent_category: Optional[str]   # 'hotel_booking', 'travel_faq', 'itinerary_planning', 'ambiguous'
    complexity: Optional[str]        # Complexity tier assigned by Supervisor: 'low', 'medium', 'high'
    objective: Optional[str]         # General objective of the user prompt
    detected_language: Optional[str] # Language of the user prompt
    intent_confidence: Optional[float] # Confidence score 0.0-1.0
    ambiguity_reason: Optional[str]    # Explanation if intent is ambiguous

    # ─── COST TRACKING ───
    tier1_input_tokens: Optional[int]
    tier1_output_tokens: Optional[int]
    tier2_input_tokens: Optional[int]
    tier2_output_tokens: Optional[int]
    estimated_cost_usd: Optional[float]

    # ─── PHASE 2: WORKFLOW MEMORY (PROCEDURAL STATE) ───
    # Keeps track of the execution plan generated by the Planner Node
    # Example: [{"id": 1, "desc": "Find hotel", "status": "pending", "result": "raw output", "findings": [...]}]
    tasks: List[Dict[str, Any]]
    current_task_id: Optional[int]
    
    # ─── PHASE 2: LOOP MANAGEMENT & SAFEGUARDS ───
    iteration_count: int         # Tracks graph cycles to enforce Max Iterations
    tool_call_count: int         # Tracks total tools invoked to enforce Budget Limits
    action_history: List[str]    # Records hashed tool calls to prevent Duplicate Actions
    rework_count: int            # Tracks Critic→Reflection rework cycles to enforce Max Rework

    # ─── EVALUATION MEMORY ───
    evaluator_feedback: Optional[str]    # Set by node_evaluator_agent — high-level feedback on response quality
    fact_check_feedback: Optional[str]   # Set by node_fact_checker — factual consistency feedback (separate field to prevent overwrite)
    evaluator_notes: Optional[str]       # Actionable rework directives from node_evaluator_agent, injected into next executor run
    needs_rework: Optional[bool]
    fact_check_result: Optional[Dict[str, Any]]
    final_answer: Optional[str]

    # ─── CONTENT/EXTRACTION PIPELINE STATE ───
    # Set by node_finding_extractor after each executor run.
    # Decouples task_manager from fragile JSON parsing of executor message content.
    raw_executor_output: Optional[str]      # Plain-text result summary extracted from executor output
    extracted_findings: List[Dict[str, Any]] # Structured List[Finding] dicts from the extractor

    # ─── CACHING ───
    cache_hit: Optional[bool]

    # ─── A/B TESTING & EVAL PIPELINE BRIDGE ───
    # Set once by node_input_guardrail; deterministic per session_id.
    # "model_a" = control group (majority traffic)
    # "model_b" = treatment group (candidate model, ~10% traffic)
    model_variant: Optional[str]

    # True when rework limit reached but response still deficient.
    # Signals human review required in Eval Pipeline dashboard.
    forced_accept: Optional[bool]

    # Eval scores from node_evaluator_agent — forwarded to Langfuse post-graph.
    # Range: 1-10 integer (as per EvaluatorOutput schema)
    tool_quality_score: Optional[int]
    evidence_quality_score: Optional[int]
    citation_quality_score: Optional[int]
    freshness_score: Optional[int]